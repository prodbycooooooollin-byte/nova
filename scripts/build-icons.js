// Builds ui/icons.js from the IBM Carbon icon set (Apache-2.0), plus Nova's own orbit glyphs for the three profiles.
const fs = require('fs'), path = require('path');
const SRC = 'C:/Users/colli/AppData/Local/Temp/claude/iconpack/node_modules/@carbon/icons/svg/32';
const OUT = process.argv[2];
const MAP = {
  back: 'chevron--left', fwd: 'chevron--right', reload: 'renew', refresh: 'renew', grid: 'grid', sliders: 'settings--adjust',
  plus: 'add', x: 'close', min: 'subtract', max: 'maximize', shield: 'security', search: 'search', search2: 'search', lock: 'locked',
  vol: 'volume--up', mute: 'volume--mute', pin: 'pin', cmd: 'terminal', archive: 'archive', layout: 'side-panel--open', palette: 'color-palette',
  layers: 'layers', keyboard: 'keyboard', code: 'code', box: 'cube', save: 'save', moon: 'asleep', gauge: 'meter', user: 'user',
  star: 'star', starf: 'star--filled', clock: 'time', download: 'download', rewind: 'recently-viewed', imp: 'document--import',
  bookmark: 'bookmark', trash: 'trash-can', open: 'launch', split: 'split-screen', globe: 'earth', check: 'checkmark', zap: 'flash',
  camera: 'camera', film: 'video', file: 'document', link: 'link', eye: 'view', info: 'information',
};
const inner = (name) => {
  const f = path.join(SRC, name + '.svg');
  if (!fs.existsSync(f)) throw new Error('missing ' + name);
  return fs.readFileSync(f, 'utf8').replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<title>.*?<\/title>/g, '').replace(/\s+/g, ' ').trim();
};
const lines = [];
for (const [k, v] of Object.entries(MAP)) lines.push(`  ${JSON.stringify(k)}: ${JSON.stringify(inner(v))},`);
// Nova's own glyphs: one, two and four orbits around a star, matching the start page and the profile cards
const ring = (rx, ry, rot, extra = '') => `<ellipse cx="16" cy="16" rx="${rx}" ry="${ry}" transform="rotate(${rot} 16 16)" fill="none" stroke-width="1.5" ${extra}/>`;
const dot = (x, y, r, extra = '') => `<circle cx="${x}" cy="${y}" r="${r}" stroke="none" ${extra}/>`;
const own = {
  'p-ultra': dot(16, 16, 3.4) + `<circle cx="16" cy="16" r="10.5" fill="none" stroke-width="1.5" stroke-dasharray="1.2 3.6" opacity=".7"/>`,
  'p-nova': dot(16, 16, 3.4) + ring(12.5, 5.6, -24) + dot(26.6, 10.5, 2.2),
  'p-complete': dot(16, 16, 3) + ring(7, 3.2, -24, 'opacity=".95"') + ring(11.5, 5.2, -24, 'opacity=".8"') + ring(14.8, 6.8, -24, 'opacity=".6"') + dot(8.8, 19.4, 1.7) + dot(26.9, 12.6, 2) + dot(5.6, 11.2, 1.4),
};
for (const [k, v] of Object.entries(own)) lines.push(`  ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
fs.writeFileSync(OUT, `// Icons: IBM Carbon Design System (Apache License 2.0, https://github.com/carbon-design-system/carbon) and Nova's own orbit glyphs.
// Generated by scripts/build-icons.js. All shapes are drawn on a 32 px grid and filled with currentColor.
const ICONS = {
${lines.join('\n')}
};
`);
console.log('wrote', Object.keys(MAP).length + Object.keys(own).length, 'icons to', OUT);
